const stampInputs = () => {
  const o = {};
  for (const f of WATCHED) {
    try { const s = fs.statSync(D(f)); o[f] = { size: s.size, sha12: ER.sha12(D(f)) }; }
    catch (e) { o[f] = { error: String((e && e.message) || e) }; }
  }
  return o;
};


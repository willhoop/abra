/* wire_ladder.js — THE RELEASE LADDER. What one night of WIRE fixes actually bought, measured once,
 * controlled, over EVERY frozen release rather than adjacent pair by adjacent pair.
 *
 *   SHOWDOWN_PATH=... node engine/wire_ladder.js                 run it, print the table
 *   SHOWDOWN_PATH=... node engine/wire_ladder.js --write         + data/wire-ladder.json
 *   SHOWDOWN_PATH=... node engine/wire_ladder.js --games 2700    the sample size (default 2700)
 *   SHOWDOWN_PATH=... node engine/wire_ladder.js --keep-arms <d> keep every arm's full artifact
 *
 * ================= WHY THIS EXISTS =================================================================
 *
 * Six wires landed on 2026-08-06/07 and each published a before/after pair. WIRE 5 then found that
 * `data/mechanics-census.json` STEERS the differential's sample — `covWant()` prefers the action
 * reaching the least-exercised census row — and sat outside the photograph. Landing a probe changed
 * which games got played, so every pair before WIRE 6 was uncontrolled and its deltas are retracted
 * (CHANGELOG 3.62.1). WIRE 4's controlled re-run moved `-damage field 3` from a published 46/45->31/31
 * to an actual 59/56->38/35: the finding was REAL AND LARGER, the numbers were wrong.
 *
 * A pairwise before/after also cannot answer the question anybody actually has, which is what the
 * NIGHT bought. TEN releases are frozen along the way (nine from 2026-08-06/07 plus WIRE 7's), so the
 * ladder is replayable rather than a re-do: every rung is run under ONE pinned census and ONE team
 * pool, which makes all eleven arms mutually comparable instead of only adjacent.
 *
 * ================= WHAT THIS FILE IS AND IS NOT ===================================================
 *
 * IT ORCHESTRATES; IT DOES NOT MEASURE. Every number below comes out of `engine/game_differential.js`
 * run as a child process, and every comparability verdict comes out of `engine/arms_comparable.js`'s
 * own `compare()`. Nothing here reimplements a rule either of them owns — CLAUDE.md's canonical-path
 * rule, and the reason `status.js` shells out to `provenance.js` instead of copying its staleness
 * logic. A second implementation of "did these two arms sample the same population" is how two files
 * come to disagree about one fact.
 *
 * ONE RUN PER ARM, NOT TWO. The arm is run with `--verbose --write` together, so the per-game
 * divergence depth parsed from stdout and the artifact written to disk describe the SAME run. Running
 * twice and joining the two would be two photographs presented as one.
 *
 * ================= THE THREE THINGS THAT MAKE THE LADDER READABLE =================================
 *
 * 1. THE CENSUS IS PINNED TO A DURABLE FILE, not to the live one. `data/mechanics-census.json` is
 *    regenerated by `tests/test-mechanics.js` and moved twice during the night these releases were
 *    cut; WIRE 6's own published artifact pinned it to a path inside an agent's scratchpad, which is
 *    unauditable the moment that session ends. `data/wire-ladder-census.pin.json` is a copy of the
 *    live census taken at 2026-08-07T08:21Z and is checked in beside the result.
 *
 * 2. THE BASELINE IS RUN TWICE, FIRST AND LAST. Nine arms sit between the two, so a drift anywhere
 *    in the ladder — the team store appending, a stray regeneration — shows up as the two baselines
 *    disagreeing. If they disagree the whole ladder is uninterpretable AND THAT IS THE FINDING; this
 *    file says so rather than averaging them.
 *
 * 3. EVERY ARM IS CHECKED AGAINST THE BASELINE, NOT AGAINST ITS NEIGHBOUR. `arms_comparable.compare`
 *    runs for all of them and a refusal is REPORTED, never worked around.
 *
 * ================= WHICH RELEASES, AND WHY EACH INTERMEDIATE IS IN ================================
 *
 * The seven named wires left seven releases (WIRE 5 changed the INSTRUMENT and cut none). Three more
 * cuts sit between them, and all three carry a REAL ENGINE CHANGE rather than a re-cut — verified by
 * diffing the manifests, which show exactly one file moving anywhere in the ladder
 * (`engine/medicham2-browser.js`; the other 22 frozen files are byte-identical across all ten
 * releases). Excluding them would silently attribute their effect to the named wire that follows,
 * which is the same misattribution WIRE 5 was written to stop.
 */

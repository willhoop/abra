/* ---- ONE ARM --------------------------------------------------------------------------------------
 * `--verbose --write` in the SAME invocation: the depth distribution parsed from stdout and the
 * artifact on disk are then the same run. A run that threw is a REFUSAL — a ladder missing a rung is
 * not a ladder, and continuing past it would publish a table with a silent hole in it. */
function runArm(arm) {
  const out = path.join(ARM_DIR, arm.id + '.json');
  const args = ['engine/game_differential.js', '--release', arm.release, '--census', CENSUS,
                '--games', String(GAMES), '--verbose', '--write', '--out', out];
  const t0 = Date.now();
  let stdout;
  try {
    stdout = execFileSync(process.execPath, args, { cwd: D(), encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  } catch (e) {
    console.error('ARM ' + arm.id + ' (release ' + arm.release + ') DID NOT COMPLETE — the ladder is '
      + 'incomplete and is not written.\n' + String((e && e.stderr) || (e && e.message) || e).slice(0, 4000));
    process.exit(4);
  }
  fs.writeFileSync(path.join(ARM_DIR, arm.id + '.log'), stdout);
  /* THE PER-GAME DEPTH, READ OFF THE DRIVER'S OWN VERBOSE LINE. `null` is a game that agreed all the
   * way through — kept as null and never as a large number, because "never diverged" and "diverged
   * late" are different events and a sentinel would let them average together. */
  const depth = [];
  for (const l of stdout.split(/\r?\n/)) {
    const m = /DIVERGES at line (\d+)/.exec(l);
    if (m) { depth.push(+m[1]); continue; }
    if (/agrees, \d+ turns/.test(l)) depth.push(null);
  }
  const j = JSON.parse(fs.readFileSync(out, 'utf8'));
  if (depth.length !== j.games) {
    console.error('ARM ' + arm.id + ': the verbose stream carries ' + depth.length + ' games and the '
      + 'artifact says ' + j.games + '. They are the same run, so they must agree — refusing.');
    process.exit(4);
  }
  return { artifact: j, depth, wall_s: +((Date.now() - t0) / 1000).toFixed(1), path: out };
}

/* ---- SUMMARY STATISTICS, ONE IMPLEMENTATION ------------------------------------------------------ */
const finite = v => v.filter(x => x != null);
const quant = (v, p) => { const s = finite(v).slice().sort((a, b) => a - b);
                          return s.length ? s[Math.min(s.length - 1, Math.floor(s.length * p))] : null; };
const mean = v => { const s = finite(v); return s.length ? +(s.reduce((a, b) => a + b, 0) / s.length).toFixed(2) : null; };
/* PAIRED, over the same games in the same order — the two arms played the identical sample, so this
 * is a paired comparison and not two independent rates. A game that never diverged is ranked deepest;
 * that is an ORDER statement (it parted later than any game that parted) and not an imputed value, so
 * it is used for the counts and excluded from the means above. */
function paired(a, b) {
  let later = 0, earlier = 0, same = 0;
  const deltas = [];
  for (let i = 0; i < a.length; i++) {
    const x = a[i] == null ? Infinity : a[i], y = b[i] == null ? Infinity : b[i];
    if (y > x) later++; else if (y < x) earlier++; else same++;
    if (a[i] != null && b[i] != null) deltas.push(b[i] - a[i]);
  }
  deltas.sort((p, q) => p - q);
  return { n: a.length, parted_later: later, parted_earlier: earlier, parted_at_the_same_line: same,
           net_later: later - earlier,
           median_delta_lines: deltas.length ? deltas[Math.floor(deltas.length / 2)] : null };
}

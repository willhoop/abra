/* build_meta_js.js — wrap the COMPETITIVE threat list as a browser global for the Tower.
 *
 *   node build/build_meta_js.js   ->  data/abra-meta.js
 *
 * The Tower's first guardians were drawn uniformly from all 289 species, which made Stunfisk and
 * Aromatisse floor bosses (Will: "wtf are these pokemon selections"). Guardians must field what the
 * format actually plays, and that is measured, not asserted: data/meta-usage.json's COMPETITIVE
 * view (the clean slice, per the Garbodor rule — never the raw ladder) ranks species by team rate
 * over 5,368 sampled competitive teams. GENERATED (S13): regenerate after refresh-site-data, never
 * edit. */
'use strict';
const fs = require('fs');
const path = require('path');
const D = (...p) => path.join(__dirname, '..', ...p);

const m = JSON.parse(fs.readFileSync(D('data', 'meta-usage.json'), 'utf8'));
const view = (m.views && m.views.competitive) || {};
const threats = (view.threats || []).map(t => ({ sp: t.sp, teamRate: t.teamRate, winRate: t.winRate }));
if (!threats.length) { console.error('no competitive threats in data/meta-usage.json'); process.exit(1); }
const out = '/* GENERATED by build/build_meta_js.js from data/meta-usage.json (competitive view, ' +
  (view.sampledTeams || '?') + ' teams) — do not edit. */\n' +
  'window.ABRA_META=' + JSON.stringify({ sampledTeams: view.sampledTeams || null, threats }) + ';\n';
fs.writeFileSync(D('data', 'abra-meta.js'), out);
console.error(`wrote data/abra-meta.js (${threats.length} ranked threats)`);

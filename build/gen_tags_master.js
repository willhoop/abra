/* gen_tags_master.js — THE single tag document. Regenerate, never edit.
 *
 *   SHOWDOWN_PATH=... node build/gen_tags_master.js
 *   node build/md_to_pdf.js docs/TAGS-MASTER.md docs/TAGS-MASTER.pdf
 *
 * Will, 2026-07-29: "NO KEEP IT ALL ONE MASTER DOCUMENT SO I CAN CONTINUALLY REFER TO IT."
 *
 * Five separate review documents had accumulated (TAGS-review, -v2, -assignments, -status-moves,
 * -abilities-review), each a snapshot of one review pass. That is exactly the state S13 exists to
 * prevent: the moment there are five, four of them are stale and nobody knows which.
 *
 * So this is one file, generated from data/tags.json and the live corpus, covering moves, abilities
 * and items together. Every count here is measured at generation time. Nothing is typed.
 *
 * The REVIEW LOG at the end is the one hand-written part, because it records decisions Will made
 * that no artifact contains -- and each entry names the mechanic, so a future run can check it.
 */
'use strict';
const path = require('path'), fs = require('fs');
const ROOT = path.join(__dirname, '..');
process.chdir(ROOT);
const CS = require(path.join(ROOT, 'engine/champions_sim.js'));
const { Dex } = CS.sim();
const dex = Dex.forFormat(CS.FORMAT);
const T = require(path.join(ROOT, 'data/tags.json'));
const F = require(path.join(ROOT, 'engine/fit_policy.js'));
const norm = s => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

/* ---- usage over the clean corpus ------------------------------------------------------------- */
const { games } = F.loadCorpus();
const U = { move: {}, ability: {}, item: {} };
let N = 0;
for (const g of games) for (const s of ['p1', 'p2']) for (const e of (g.sheets && g.sheets[s]) || []) {
  N++;
  if (e.ability) U.ability[norm(e.ability)] = (U.ability[norm(e.ability)] || 0) + 1;
  if (e.item) U.item[norm(e.item)] = (U.item[norm(e.item)] || 0) + 1;
  for (const m of e.moves || []) U.move[norm(m)] = (U.move[norm(m)] || 0) + 1;
}
const pct = n => (n / N * 100).toFixed(1) + '%';
const tagInfo = {}; for (const t of T.tags) tagInfo[t.tag] = t;

const L = [];
const P = s => L.push(s);

/* ---- header ---------------------------------------------------------------------------------- */
P('# ABRA — the tag master');
P('');
P('*Generated by `build/gen_tags_master.js` from `data/tags.json` and the live corpus. Do not edit');
P('this file — regenerate it. Every count is measured at generation time over the');
P('**' + N.toLocaleString() + '** team-sheet entries in the clean corpus.*');

/* ---- MEGA ABILITY SWAPS -----------------------------------------------------------------------
 * Will: "who tf running damp u aint giving me the mega abilities."
 *
 * He was reading Damp at 436 sheets and knew nobody plays Damp -- it is base-forme Swampert, which
 * megas into Swift Swim. The team sheet publishes the BASE forme's ability, and the ability that
 * will actually be on the field is the mega's. 28% of sheet entries hold a stone and 90% of those
 * change ability, so roughly a quarter of every Pokemon in the format is listed under an ability it
 * will not have. This section exists so the usage tables above are read with that in mind. */
const ab1 = sp => (sp && sp.abilities) ? Object.values(sp.abilities)[0] : null;
{
  let stones = 0, changed = 0;
  const swap = {};
  for (const g of games) for (const s of ['p1', 'p2']) for (const e of (g.sheets && g.sheets[s]) || []) {
    const it = dex.items.get(norm(e.item || ''));
    if (!it || !it.megaStone) continue;
    const base = dex.species.get(norm(e.species));
    const mega = dex.species.get(it.megaStone[base.baseSpecies] || Object.values(it.megaStone)[0]);
    const a = ab1(mega);
    if (!a) continue;
    stones++;
    if (norm(e.ability) !== norm(a)) {
      changed++;
      const k = base.name + '|' + e.ability + '|' + a;
      swap[k] = (swap[k] || 0) + 1;
    }
  }
  P('# MEGA ABILITIES — the sheet does not say what will be on the field');
  P('');
  P('**' + stones.toLocaleString() + '** sheet entries (' + pct(stones) + ') hold a mega stone, and **' +
    (changed / stones * 100).toFixed(1) + '%** of those change ability on evolution — **' +
    changed.toLocaleString() + '** entries, about one Pokémon in four.');
  P('');
  P('Every ability count in this document is the ability *written on the sheet*. For these, that is');
  P('not the ability the engine will face. Staraptor is the dangerous one: the sheet says Intimidate');
  P('and the field says **Contrary**, which inverts every stat change.');
  P('');
  P('| species | sheet says | field says | entries |');
  P('|---|---|---|---:|');
  for (const [k, c] of Object.entries(swap).sort((a, b) => b[1] - a[1])) {
    const [sp, from, to] = k.split('|');
    P('| ' + sp + ' | ' + from + ' | **' + to + '** | ' + c.toLocaleString() + ' |');
  }
  P('');
  P('---');
  P('');
}

/* ---- the sections ----------------------------------------------------------------------------
 * ONE ROW PER ENTITY, SORTED BY USAGE -- not grouped by tag. Will: "i need it [like] before where
 * it had the usage based tables for each move and then all the tags for that move... not sorted by
 * tags."
 *
 * That is the right shape for the job. Grouping by tag answers "who has this tag", which is useful
 * once you already suspect a tag is wrong. Reviewing means reading down the moves people actually
 * click and asking whether each one's tags describe it -- and a move with a MISSING tag is
 * invisible in a tag-grouped view, because it simply never appears in the group it should be in.
 * That is exactly how Clanging Scales and Super Fang stayed hidden.
 *
 * The tag-grouped view is kept afterwards as a cross-reference, since it is the faster way to audit
 * a single suspicious category once one is identified. */
function entityTable(kind, table, usage, title, blurb) {
  const rows = Object.entries(table)
    .map(([id, rec]) => ({ id, rec, u: usage[id] || 0 }))
    .filter(r => r.u > 0)
    .sort((a, b) => b.u - a.u);

  P('# ' + title);
  P('');
  P(blurb);
  P('');
  const one = kind === 'abilities' ? 'ability' : kind.replace(/s$/, '');
  P('Every ' + one + ' that appears on a real sheet, in usage order, with the tags it carries.');
  P('`untagged` is deliberate — it means the thing genuinely has no mechanic, like Hydro Pump.');
  P('');
  P('| ' + one + ' | on sheets | share | tags |');
  P('|---|---:|---:|---|');
  for (const r of rows) {
    const o = kind === 'moves' ? dex.moves.get(r.id) : kind === 'items' ? dex.items.get(r.id) : dex.abilities.get(r.id);
    const tags = (r.rec.tags || []).length ? r.rec.tags.map(t => '`' + t + '`').join(' ') : '`untagged`';
    P('| ' + ((o && o.name) || r.id) + ' | ' + r.u.toLocaleString() + ' | ' + pct(r.u) + ' | ' + tags + ' |');
  }
  P('');
  P('---');
  P('');
  return rows.length;
}

function section(kind, table, usage, title, blurb) {
  const byTag = {};
  for (const [id, rec] of Object.entries(table))
    for (const t of rec.tags || []) (byTag[t] = byTag[t] || []).push([id, usage[id] || 0]);
  const rows = Object.entries(byTag).map(([t, v]) => {
    v.sort((a, b) => b[1] - a[1]);
    return { tag: t, mem: v, tot: v.reduce((s, x) => s + x[1], 0) };
  }).sort((a, b) => b.tot - a.tot);

  P('# ' + title);
  P('');
  P(blurb);
  P('');
  P('`read` means a probe string for the tag appears in `board.js` or the damage engine. **NOT READ**');
  P('means the tag is correct and nothing consumes it yet — a wiring backlog, not an error.');
  P('');
  /* TABLES, RESTORED. Will tried the inline version and called it: "no go back to the usage based
   * tables that was needed apparently this sucks." He is right that a scannable usage column is
   * what makes a review possible at all.
   *
   * The original spacing complaint was never caused by tables as such -- it was
   * page-break-inside:avoid on all 132 of them, so any table too tall for the remaining space
   * jumped wholesale to the next page and left the rest of the current one blank. Tables now break
   * across pages freely and the holes go away without giving up the columns. */
  for (const r of rows) {
    const i = tagInfo[r.tag] || {};
    const shown = r.mem.filter(x => x[1] > 0);
    P('### `' + r.tag + '` — ' + pct(r.tot) + ', ' + r.mem.length + ' ' + kind +
      (i.used ? '' : ' — **NOT READ**'));
    P('');
    P('*' + (i.param || '?') + '*');
    P('');
    if (shown.length) {
      /* EXHAUSTIVE. Will: "i dont [want] tables that long, but without an exhaustive list we might
       * miss something." A truncated list is precisely how a mis-tagged move stays hidden. */
      P('| ' + kind.replace(/s$/, '') + ' | on sheets | share |');
      P('|---|---:|---:|');
      for (const [id, c] of shown) {
        const o = kind === 'moves' ? dex.moves.get(id) : kind === 'items' ? dex.items.get(id) : dex.abilities.get(id);
        P('| ' + ((o && o.name) || id) + ' | ' + c.toLocaleString() + ' | ' + pct(c) + ' |');
      }
      const never = r.mem.length - shown.length;
      if (never) P('');
      if (never) P('*' + never + ' more carry this tag but appear on no sheet in the corpus.*');
    } else {
      P('*Legal in the format, never brought.*');
    }
    P('');
  }
  P('---');
  P('');
  return rows.length;
}


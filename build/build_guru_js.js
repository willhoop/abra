/* build_guru_js.js — generate data/guru.js, the browser bundle the site's GURU booth reads.
 *
 * WHY THIS EXISTS. As of 2026-07-25 data/guru.js had NO GENERATOR. Its only reference anywhere in
 * the repository was engine/sanity_check.py checking that the file exists. It had been produced once
 * — by hand or by a script since deleted — and could not be refreshed, so the site's matchup
 * authority was frozen at whatever the store looked like on 2026-07-23: two days stale, computed
 * before the store was repaired, and computed on the UNFILTERED store.
 *
 * That is S1 in the most user-visible place in the project: a derived artifact with no definitive
 * source and no way to regenerate it.
 *
 * guru.py writes data/guru-matchups.json. This projects that into the shape the site expects
 * (window.GURU with archetypes / decisive / matrix / n_games) and adds the provenance the booth
 * needs in order to describe its own population honestly.
 *
 *   node build/build_guru_js.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const D = (...p) => path.join(ROOT, ...p);

const SRC = D('data', 'guru-matchups.json');
if (!fs.existsSync(SRC)) {
  console.error(`missing ${path.relative(ROOT, SRC)} — run: python engine/guru.py`);
  process.exit(1);
}
const g = JSON.parse(fs.readFileSync(SRC, 'utf8'));

/* Carry the provenance into the bundle. The booth previously claimed "5,199 real Champions games"
 * from a hardcoded string in the HTML, with no way for a reader to tell which population that was.
 * Now the file says. */
const out = {
  archetypes: g.archetypes || Object.keys(g.matrix || {}),
  decisive: g.decisive || [],
  matrix: g.matrix || {},
  n_games: g.n_games != null ? g.n_games : (g.games || null),
  n_decisive: (g.decisive || []).length,
  predictive_test: g.predictive_test || null,
  provenance: {
    generated: new Date().toISOString().slice(0, 10),
    generator: 'build/build_guru_js.js from data/guru-matchups.json',
    filtered: !process.env.ABRA_UNFILTERED,
    note: (g.decisive || []).length === 0
      ? 'ZERO statistically-decisive matchups on this population. The matrix is descriptive structure; it is not evidence that one archetype beats another.'
      : 'A matchup is called decisive only at n>=30 with a Wilson interval excluding 50%.',
  },
};

fs.writeFileSync(D('data', 'guru.js'),
  '/* GENERATED by build/build_guru_js.js from data/guru-matchups.json. Do not hand-edit. */\n' +
  'window.GURU=' + JSON.stringify(out) + ';\n');

console.log(`wrote data/guru.js — ${out.archetypes.length} archetypes, ${out.n_decisive} decisive, ` +
            `n_games=${out.n_games}`);
if (out.n_decisive === 0) {
  console.log('  NOTE: zero decisive matchups. The site must not present this matrix as evidence of');
  console.log('  archetype superiority — every cell is indistinguishable from a coin flip.');
}

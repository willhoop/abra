/* build_mag_variables.js — regenerate docs/MAG-VARIABLES.md from the live weight files.
 *
 *   node build/build_mag_variables.js
 *
 * WHY IT IS GENERATED
 * -------------------
 * A document listing 46 weights is hand-maintained state (S13) describing the very thing it would go
 * stale against. The weights change every time anyone refits — they changed four times tonight — and
 * a table of numbers nobody regenerated is worse than no table, because it reads as current.
 *
 * So the numbers come from data/policy-weights.json and the plain-English lines come from the
 * FEATURES block in engine/board.js via data/mag.js. The prose BELOW the tables is written by hand
 * and preserved: it explains why the signs are odd, and that reasoning does not change when a weight
 * moves by 0.02.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const D = (...p) => path.join(__dirname, '..', ...p);

const W = JSON.parse(fs.readFileSync(D('data', 'policy-weights.json'), 'utf8'));
const M = require(D('data', 'mag.js')).MAG;
const doc = M.featDoc || {};
const se = W.standardErrors || [];

/* THE NO-POPULARITY COLUMN IS PRINTED BESIDE TODAY'S WEIGHTS, SO IT HAS TO BE COMPARABLE.
 *
 * This used to be `try { read } catch { np = null }`, which catches a MISSING file and nothing else.
 * On 2026-08-02 the file it was reading carried **47 features against board.js's 56**, fitted on
 * 2026-07-27 over 3,340 games and 82,836 decisions — against today's 7,454 and 196,803. Every
 * feature whose name happened to survive got a number from a different feature set on a different
 * corpus, printed column-by-column next to the live weight as though the two were the same
 * experiment. The nine features that did not exist yet showed an em dash, which reads as "not
 * applicable" rather than "this table is comparing two different models".
 *
 * engine/magnemite.js already refuses a vector whose feature list disagrees, for exactly this
 * reason. A document generator has no business being more permissive than the player: a wrong number
 * in a published table is read by people who cannot check it. So the mismatch is now LOUD and the
 * column is dropped rather than filled with a stale one.
 *
 * Regenerate with:  DROP=priorLogP OUT_WEIGHTS=data/policy-weights-nopop.json node engine/fit_policy.js */
let np = {};
let NPW = null;
try {
  const NP = JSON.parse(fs.readFileSync(D('data', 'policy-weights-nopop.json'), 'utf8'));
  if ((NP.features || []).join(',') !== W.features.join(',')) {
    console.error(`  no-popularity column DROPPED: data/policy-weights-nopop.json has ` +
      `${(NP.features || []).length} features against the live vector's ${W.features.length}, ` +
      `so the two columns are not the same experiment.`);
    console.error('  refit it:  DROP=priorLogP OUT_WEIGHTS=data/policy-weights-nopop.json node engine/fit_policy.js');
    np = null;
  } else {
    NP.features.forEach((f, i) => { np[f] = NP.weights[i]; });
    NPW = NP;
  }
} catch (e) { np = null; }

const rows = W.features.map((f, i) => ({
  f, w: W.weights[i], se: se[i] || 0,
  np: np ? np[f] : null,
  en: (doc[f] || {}).en || '', grp: (doc[f] || {}).group || 'other',
}));

const groups = {};
for (const r of rows) (groups[r.grp] = groups[r.grp] || []).push(r);

let md = '# MAG — every variable, what it means, and why its weight is what it is\n\n';
md += `**${new Date().toISOString().slice(0, 10)}** · ${rows.length} features · ` +
      `fitted on ${(W.corpus && W.corpus.decisions ? W.corpus.decisions.toLocaleString() : 'the')} human decisions ` +
      `from ${(W.corpus && W.corpus.games ? W.corpus.games.toLocaleString() : '')} clean open-sheet games\n\n`;
md += 'GENERATED by `build/build_mag_variables.js` from the live weight file. Do not hand-edit the tables.\n\n';
md += 'Nobody typed these numbers. Each is fitted: the model is shown a real human decision and all the\n';
md += 'options that person had, and the weights are nudged until the option they actually clicked comes\n';
md += 'out most likely. So every weight answers one question — **what makes a human more likely to click\n';
md += 'this** — and never *what wins*.\n\n';
md += '`ZERO` marks a weight whose 95% interval contains zero: the data cannot tell it from no effect.\n\n';
/* THE INTERPRETATION IS DERIVED, NOT TYPED.
 *
 * This line used to read "the experiment that showed the facts were being crowded out" — a hardcoded
 * conclusion about a result that turned out to be an artifact. `DROP=` zeroed the feature on move rows
 * only, not on voluntary-switch rows, so the no-popularity fit still contained popularity and handed it
 * a confident −1.73 (SE 0.05). With the drop actually applied, removing popularity makes MAG WORSE at
 * predicting human clicks. See CHANGELOG 3.23.0.
 *
 * A generated document that hardcodes what its own numbers mean is S13 with extra steps: the table
 * refreshed on every refit and the sentence above it did not. The comparison is now read out of the two
 * weight files, so the sentence cannot outlive the result it describes. */
if (np) {
  const acc = j => (j && j.heldOut && j.heldOut.boardAware) ? j.heldOut.boardAware.acc : null;
  const a1 = acc(W), a2 = acc(NPW);
  md += 'The last column is the same fit with **popularity removed entirely**.\n\n';
  if (a1 != null && a2 != null) {
    const d = 100 * (a2 - a1);
    md += `On held-out human decisions the full model picks the option the person actually clicked ` +
          `**${(100 * a1).toFixed(1)}%** of the time; without popularity, **${(100 * a2).toFixed(1)}%** — ` +
          `${d >= 0 ? 'a gain' : '**a loss**'} of ${Math.abs(d).toFixed(1)} points.` +
          (d < 0
            ? ' So popularity carries real signal and is not crowding the board facts out. An earlier' +
              ' version of this document asserted the opposite, from a fit whose `DROP=` reached only' +
              ' half the corpus.\n\n'
            : ' Both figures are read from the weight files, never typed here.\n\n');
  }
}

for (const [g, list] of Object.entries(groups)) {
  md += `\n## ${g}\n\n`;
  md += np ? '| feature | weight | no-popularity | what it means |\n|---|---:|---:|---|\n'
           : '| feature | weight | what it means |\n|---|---:|---|\n';
  list.sort((a, b) => b.w - a.w);
  for (const r of list) {
    const zero = (r.w - 1.96 * r.se < 0 && r.w + 1.96 * r.se > 0) ? ' `ZERO`' : '';
    const w = (r.w >= 0 ? '+' : '') + r.w.toFixed(3) + zero;
    const n = r.np == null ? '—' : (r.np >= 0 ? '+' : '') + r.np.toFixed(3);
    md += np ? `| \`${r.f}\` | ${w} | ${n} | ${r.en} |\n`
             : `| \`${r.f}\` | ${w} | ${r.en} |\n`;
  }
}

/* The hand-written reasoning is kept verbatim across rebuilds: it explains WHY the signs look wrong,
 * and that does not stop being true when a weight moves. Split on the marker so the tables above are
 * regenerated and everything below is preserved. */
const MARK = '\n---\n\n# Why the weights look wrong';
const outPath = D('docs', 'MAG-VARIABLES.md');
let tail = '';
try {
  const existing = fs.readFileSync(outPath, 'utf8');
  const i = existing.indexOf(MARK);
  if (i >= 0) tail = existing.slice(i);
} catch (e) { /* first run */ }
if (!tail) console.error('  note: no hand-written reasoning section found to preserve');

fs.writeFileSync(outPath, md + tail);
console.log(`docs/MAG-VARIABLES.md — ${rows.length} features, ${Object.keys(groups).length} groups` +
            (tail ? ', reasoning section preserved' : ''));

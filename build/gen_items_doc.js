/* gen_items_doc.js — the ITEMS review list, standalone. Regenerate, never edit.
 *
 *   SHOWDOWN_PATH=... node build/gen_items_doc.js
 *   node build/md_to_pdf.js docs/ITEMS-review.md docs/ITEMS-review.pdf
 *
 * Will, 2026-07-29: "remove all mega stones from the item list i dont need em" / "and just send me
 * the item list."
 *
 * Mega stones are 28% of held items and carry exactly one tag between them, so they are pure noise
 * in a review whose job is to check that each item's tags describe what it does. They are dropped
 * here by the megaStone dex field rather than by name — their ability consequences already live in
 * the MEGA ABILITIES section of the master document.
 */
'use strict';
const path = require('path'), fs = require('fs');
const ROOT = path.join(__dirname, '..');
process.chdir(ROOT);
const CS = require(path.join(ROOT, 'engine/champions_sim.js'));
const { Dex } = CS.sim();
const dex = Dex.forFormat(CS.FORMAT);
const T = require(path.join(ROOT, 'data/tags.json'));
const F = require(path.join(ROOT, 'engine/fit_policy.js'));
const norm = s => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

const { games } = F.loadCorpus();
const use = {}; let N = 0, stoneN = 0;
for (const g of games) for (const s of ['p1', 'p2']) for (const e of (g.sheets && g.sheets[s]) || []) {
  N++;
  if (!e.item) continue;
  const id = norm(e.item);
  const it = dex.items.get(id);
  if (it && it.megaStone) { stoneN++; continue; }        /* dropped by dex field, not by name */
  use[id] = (use[id] || 0) + 1;
}
const held = Object.values(use).reduce((a, b) => a + b, 0);
const pct = n => (n / held * 100).toFixed(1) + '%';

const rows = Object.entries(T.items)
  .map(([id, rec]) => ({ id, rec, u: use[id] || 0 }))
  .filter(r => r.u > 0)
  .sort((a, b) => b.u - a.u);

const L = []; const P = s => L.push(s);
P('# ITEMS — the review list');
P('');
P('*Generated by `build/gen_items_doc.js`. Do not edit — regenerate. Counts are measured at build');
P('time over the **' + N.toLocaleString() + '** team-sheet entries in the clean corpus.*');
P('');
P('**Mega stones are excluded** — ' + stoneN.toLocaleString() + ' held items, ' +
  (stoneN / (stoneN + held) * 100).toFixed(0) + '% of the total, carrying one tag between them.');
P('They were pure noise here; what they actually change is the *ability*, which lives in the MEGA');
P('ABILITIES section of the master document. Dropped by the `megaStone` dex field, not by name.');
P('');
P('That leaves **' + rows.length + '** distinct items across **' + held.toLocaleString() + '** holders.');
P('');
P('`untagged` is deliberate — it means the item genuinely has no mechanic worth modelling.');
P('');
P('| item | on sheets | share | tags | parameters |');
P('|---|---:|---:|---|---|');
for (const r of rows) {
  const o = dex.items.get(r.id);
  const tags = (r.rec.tags || []).length ? r.rec.tags.map(t => '`' + t + '`').join(' ') : '`untagged`';
  /* Show the actual numbers, since a tag without its parameter is what most of tonight's
   * corrections turned out to be. */
  const ps = Object.values(r.rec.params || {})
    .map(v => JSON.stringify(v))
    .filter(v => v && v !== '{}' && v !== 'true')
    .join(' ')
    .replace(/[{}"]/g, '')
    .replace(/,/g, ', ');
  P('| ' + ((o && o.name) || r.id) + ' | ' + r.u.toLocaleString() + ' | ' + pct(r.u) + ' | ' +
    tags + ' | ' + (ps.length > 96 ? ps.slice(0, 96) + '…' : ps) + ' |');
}
P('');
P('---');
P('');
P('## What changed in this pass');
P('');
P('**Sitrus Berry** — the tag named the *trigger* and not the amount. It fires at **1/2** HP and');
P('restores **1/4**, which are two different numbers the kill calculation needs separately: a target');
P('at 55% is not in range of what looks lethal.');
P('');
P('**Life Orb** — recorded ×1.3 and not the **1/10 max HP it costs on every attack**, so the item');
P('read as free. Its membership was also a name hardcode (`/^(lifeorb)$/`); both now come from the');
P('handlers.');
P('');
P('**Type-boost items** were a 24-name regex — `charcoal|blackglasses|mysticwater|…` — which');
P('silently omits anything it forgot. Now derived from the handler, which names both the type and');
P('the factor: **18 items** on sheets, each with its own type, all at ×1.2.');
P('');
P('**Focus Sash and Sturdy** already shared `survivesFromFull`, item and ability under one tag —');
P('that linkage was correct before this pass.');
P('');
P('**Leftovers and Leech Seed** now share `perTurnHP`: +1/16 to the holder against −1/8 moved from');
P('the target to the user. Leech Seed had only `statusCategory`, so its drain was recorded nowhere.');
P('');
P('**Figy Berry** is on **0 sheets** and is correctly absent — the 0.5% floor doing its job.');

fs.writeFileSync(path.join(ROOT, 'docs/ITEMS-review.md'), L.join('\n'));
console.log('wrote docs/ITEMS-review.md — ' + rows.length + ' items, ' +
  stoneN.toLocaleString() + ' mega stones excluded');

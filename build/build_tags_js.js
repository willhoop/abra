/* build_tags_js.js — wrap data/tags.json as a browser global.
 *
 *   node build/build_tags_js.js   ->  data/abra-tags.js
 *
 * engine/medicham2-browser.js reads window.ABRA_TAGS in the browser and DEGRADES to a null lookup
 * when it is absent — which is exactly how the live site has been running: every tag wire scored
 * x1.0 client-side while the node engine scored the real numbers. This file is the missing carrier.
 * GENERATED (S13): the content is data/tags.json verbatim; regenerate after any tag_dex run, never
 * edit. A page that ships it must load it BEFORE the engine script. */
'use strict';
const fs = require('fs');
const path = require('path');
const D = (...p) => path.join(__dirname, '..', ...p);

const tags = fs.readFileSync(D('data', 'tags.json'), 'utf8');
JSON.parse(tags); // refuse to wrap a corrupt artifact
const out = '/* GENERATED by build/build_tags_js.js from data/tags.json — do not edit. */\n' +
            'window.ABRA_TAGS=' + tags.trim() + ';\n';
fs.writeFileSync(D('data', 'abra-tags.js'), out);
process.stderr.write(`wrote data/abra-tags.js (${(out.length / 1024).toFixed(0)}KB)\n`);

/* build_tags_js.js — wrap data/tags.json as a browser global.
 *
 *   node build/build_tags_js.js            ->  data/abra-tags.js
 *   node build/build_tags_js.js --check   exit non-zero if the committed data/abra-tags.js is not
 *                                         what this script would write from data/tags.json
 *
 * engine/medicham2-browser.js reads window.ABRA_TAGS in the browser and DEGRADES to a null lookup
 * when it is absent — which is exactly how the live site has been running: every tag wire scored
 * x1.0 client-side while the node engine scored the real numbers. This file is the missing carrier.
 * GENERATED (S13): the content is data/tags.json verbatim; regenerate after any tag_dex run, never
 * edit. A page that ships it must load it BEFORE the engine script.
 *
 * WHY --check EXISTS (2026-08-25). NOTHING COMPARED THE TWO FILES. On 2026-08-24 a tag_dex run at
 * 23:37 rewrote data/tags.json and data/abra-tags.js was left at its 22:59 content; both were then
 * committed, so HEAD carried a node engine and a browser engine that disagreed about three moves.
 * It was noticed only because a release cut happened to look, and an earlier instance of the same
 * drift had run for two days. That is the pair this repo has already paid for twice — see
 * build/build_guru_js.js's --check and tests/test-guru-derived.js, and CLAUDE.md: "a derived
 * artifact is not a fact until something compares it to its source."
 *
 * The comparison is against what THIS script would write, not against a re-implementation of the
 * wrapper, so it stays correct if the wrapper ever changes shape. */
'use strict';
const fs = require('fs');
const path = require('path');
const D = (...p) => path.join(__dirname, '..', ...p);
const CHECK = process.argv.includes('--check');

const tags = fs.readFileSync(D('data', 'tags.json'), 'utf8');
JSON.parse(tags); // refuse to wrap a corrupt artifact
const out = '/* GENERATED by build/build_tags_js.js from data/tags.json — do not edit. */\n' +
            'window.ABRA_TAGS=' + tags.trim() + ';\n';

if (!CHECK) {
  fs.writeFileSync(D('data', 'abra-tags.js'), out);
  process.stderr.write(`wrote data/abra-tags.js (${(out.length / 1024).toFixed(0)}KB)\n`);
  process.exit(0);
}

/* --check. A byte comparison is the whole test — the payload is tags.json verbatim, so anything
 * that differs is drift. What follows the verdict is only there to say WHICH rows moved, because a
 * failure that reports "809036 bytes vs 767856" is one somebody waives instead of acting on. */
let disk = null;
try { disk = fs.readFileSync(D('data', 'abra-tags.js'), 'utf8'); }
catch (e) { console.error(`build_tags_js --check: cannot read data/abra-tags.js — ${e.message}`);
            console.error('  fix: node build/build_tags_js.js'); process.exit(1); }

if (disk === out) {
  console.log('data/abra-tags.js is exactly what data/tags.json would produce.');
  process.exit(0);
}

console.error('data/abra-tags.js DOES NOT MATCH data/tags.json — the browser engine and the node');
console.error('engine are reading different rulebooks.');
/* The three reads below are each their own failure and each says so. A wrapper whose shape changed
 * makes `.match()` null, and `[1]` would throw a TypeError that names nothing. */
const m = disk.match(/window\.ABRA_TAGS=([\s\S]*);\s*$/);
if (!m) {
  console.error('  the wrapper no longer has the shape `window.ABRA_TAGS=<json>;` — regenerate.');
} else {
  let src = null, had = null;
  try { src = JSON.parse(tags); } catch (e) { console.error(`  data/tags.json is not JSON — ${e.message}`); }
  try { had = JSON.parse(m[1]); } catch (e) { console.error(`  the shipped payload is not JSON — ${e.message}`); }
  if (src && had) {
    console.error(`  tags.json generated ${src.generated}   abra-tags.js generated ${had.generated}`);
    const S = JSON.stringify;
    for (const k of new Set([...Object.keys(src), ...Object.keys(had)])) {
      if (S(src[k]) === S(had[k])) continue;
      const a = src[k], b = had[k];
      if (a && b && typeof a === 'object' && typeof b === 'object') {
        /* Arrays are named by their row's own `tag`/`name` rather than by index — `tags` is a list,
         * and "index 210 differs" is not something anybody can act on. */
        const label = r => (Array.isArray(a) ? ((a[r] && (a[r].tag || a[r].name)) || `#${r}`) : r);
        const rows = [...new Set([...Object.keys(a), ...Object.keys(b)])].filter(r => S(a[r]) !== S(b[r]));
        console.error(`  ${k}: ${rows.length} row(s) differ — ${rows.slice(0, 8).map(label).join(', ')}` +
                      (rows.length > 8 ? ' …' : ''));
      } else {
        console.error(`  ${k}: differs`);
      }
    }
  }
}
console.error('  fix: node build/build_tags_js.js');
process.exit(1);
